#!/bin/ksh
# provision-group-capsule.sh: an own-domain body's capsule block and its pair.
#
# Usage:
#   doas ksh scripts/provision-group-capsule.sh <domain> <site-account>
#        ksh scripts/provision-group-capsule.sh --self-test
#
# Runs ON the box as root, from the drain's group intent, after
# scripts/provision-member.sh has built the site owner's tree.
#
# What it writes, and why each shape:
#
#   /etc/ssl/capsule-<domain>.cnf             root:wheel 0644
#   /etc/ssl/capsule-<domain>.crt             root:wheel 0644
#   /etc/ssl/private/capsule-<domain>.key     root:wheel 0600
#   /etc/gmid.d/<domain>.conf                 root:wheel 0644
#
# The capsule does not use ACME. A gemini client pins the certificate it was
# shown, so a ninety-day renewal would break every reader's pin, and a body's
# capsule therefore gets its own self-signed pair, generated once with a ten-year
# life and never renewed. The pair is not the platform's shared
# capsule-kyriakon.net pair: this is a second registered domain, and nothing under
# kyriakon.net carries its name.
#
# The pair is generated by openssl req -x509 driven from a configuration file,
# not from command-line extension flags, because the LibreSSL in the base system
# carries the configuration route and the OpenSSL 3 flags are not there. The
# configuration file is written by this script, so the invocation and the
# extensions cannot drift apart.
#
# It is generated once. A run that finds both halves leaves them alone, because a
# regeneration is a prompt for every reader of this capsule. A run that finds one
# half missing regenerates both, because half a pair serves nothing.
#
# The block is one server on port 1965 with the site owner's gemini root, the
# .git block, and the domain's pair. gmid chroots to /home/www, so root
# "/<site-account>.kyriakon.net/gemini" is that account's own tree, and the cert
# and key paths stay absolute because gmid.conf(5) makes those two the exceptions
# to the chroot rule. The .git block is there because the gemini root is a
# checkout the body uploads over sftp: without it the capsule would serve the
# whole history, including anything deleted from the working tree.
#
# The index and the reload are not this script's job. /etc/gmid.d/index.conf is
# regenerated and gmid is checked with gmid -n and then reloaded by
# scripts/cron-apply.sh --web, once for every generated file at once.
#
# Env: none. The self-test rebinds this script's own paths to a throwaway tree
# under TMPDIR, so it needs no root and touches nothing outside it.
#
# Not this script's job: the site owner's tree (scripts/provision-member.sh), the
# httpd vhosts (scripts/provision-group-web.sh), the acme-client block
# (scripts/provision-group-acme.sh), the index, or the reload.

set -euo pipefail

# The private key half is created under this umask, so a key file openssl creates
# is never readable by anyone else even before the chmod below runs.
umask 077

# The base system's LibreSSL, which the runbook's step and this script agree on.
openssl=/usr/bin/openssl

gmid_d=/etc/gmid.d
ssl_dir=/etc/ssl
ssl_private=/etc/ssl/private
public_root=/home/www
conf_owner="root:wheel"

usage() {
	cat >&2 <<'USAGE'
usage: doas ksh provision-group-capsule.sh <domain> <site-account>
       ksh provision-group-capsule.sh --self-test
USAGE
	exit 2
}

die() {
	printf 'provision-group-capsule: %s\n' "$*" >&2
	exit 1
}

# A validated FQDN: labels of lowercase letters, digits and hyphens, at least two
# of them, and no label starting or ending with a hyphen. It is the stem of the
# generated file, a server name and a path component under /etc/ssl.
domain_ok() {
	typeset name="$1"
	[ "${#name}" -le 253 ] || return 1
	case "$name" in
	*.*) ;;
	*) return 1 ;;
	esac
	printf '%s' "$name" | grep -Eq '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$'
}

# The site owner is a member account: the same charset add-user.sh applies,
# because it is a path component under /home/www.
account_ok() {
	printf '%s' "$1" | grep -Eq '^[a-z0-9][a-z0-9._-]{0,31}$'
}

# The paths, as functions so the self-test rebinds the directories once.
capsule_cnf() { printf '%s/capsule-%s.cnf' "$ssl_dir" "$domain"; }
capsule_cert() { printf '%s/capsule-%s.crt' "$ssl_dir" "$domain"; }
capsule_key() { printf '%s/capsule-%s.key' "$ssl_private" "$domain"; }
group_conf() { printf '%s/%s.conf' "$gmid_d" "$domain"; }
site_public() { printf '%s/%s.kyriakon.net' "$public_root" "$account"; }

# --- the pair ----------------------------------------------------------------

# The extension requests: the body's domain as the only name, and an end-entity
# certificate rather than a CA, marked critical so a client cannot read it as one
# that may sign.
capsule_cnf_body() {
	cat <<EOF
# The extension requests for the $domain capsule pair. Written by
# scripts/provision-group-capsule.sh, which is the only thing that runs openssl
# on it, so the pair and the requests for it cannot drift apart.

[ req ]
default_bits		= 4096
default_md		= sha256
distinguished_name	= subject
prompt			= no
x509_extensions		= capsule

[ subject ]
CN			= $domain

[ capsule ]
subjectAltName		= DNS:$domain
basicConstraints	= critical, CA:FALSE
EOF
}

pair_present() {
	[ -f "$(capsule_cert)" ] && [ -f "$(capsule_key)" ]
}

write_capsule_cnf() {
	typeset target candidate
	target=$(capsule_cnf)
	candidate="$target.new.$$"
	capsule_cnf_body > "$candidate"
	if [ -f "$target" ] && cmp -s "$candidate" "$target"; then
		rm -f "$candidate"
		return 0
	fi
	chmod 0644 "$candidate"
	mv "$candidate" "$target"
	printf 'capsule pair: %s written\n' "$target"
	return 0
}

ensure_capsule_pair() {
	typeset cert key generated fingerprint

	cert=$(capsule_cert)
	key=$(capsule_key)

	# The requests are kept in step with the script that runs openssl, whether
	# this is the first generation or a repair.
	write_capsule_cnf

	if pair_present; then
		printf 'capsule pair: %s already holds both halves, left alone\n' "$cert"
		return 0
	fi

	# Generating over one half is not a repair: the two halves are one
	# certificate, so a missing half means a new pair, and a new pair is a prompt
	# for every reader of this capsule.
	generated=no
	if [ -e "$cert" ] || [ -e "$key" ]; then
		printf 'capsule pair: only one half was there, so the pair is regenerated.\n'
		printf '  Every reader trusts the new certificate once, and the fingerprint the\n'
		printf '  account page publishes has to be updated: docs/runbook.md,\n'
		printf '  "Provision own-domain hosting".\n' >&2
		generated=yes
	fi

	if ! "$openssl" req -x509 -new -nodes -days 3650 -config "$(capsule_cnf)" \
		-keyout "$key" -out "$cert"; then
		die "$openssl req failed; $cert and $key may be half written, remove both and run this again"
	fi
	chmod 0644 "$cert"
	chmod 0600 "$key"

	for f in "$cert" "$key"; do
		[ -s "$f" ] || die "$f is empty after the generation step"
	done
	"$openssl" x509 -in "$cert" -noout >/dev/null 2>&1 \
		|| die "$cert does not parse as a certificate"
	[ "$(stat -f '%Lp' "$key")" = 600 ] || die "$key is not mode 0600"

	if [ "$generated" = no ]; then
		printf 'capsule pair: generated at %s (ten years, %s)\n' "$cert" "$domain"
	fi
	# The fingerprint and the date it changed, which is what the account page
	# carries. Printed because a human pastes it there: nothing regenerates the
	# pair on a schedule.
	fingerprint=$("$openssl" x509 -in "$cert" -noout -fingerprint -sha256 | sed 's/^.*=//')
	printf 'capsule fingerprint (account page): %s, changed %s\n' "$fingerprint" "$(date +%Y-%m-%d)"
	return 0
}

# --- the block ---------------------------------------------------------------

group_conf_body() {
	printf 'server "%s" {\n' "$domain"
	printf '\tlisten on * port 1965\n'
	printf '\n'
	printf '\tcert "%s"\n' "$(capsule_cert)"
	printf '\tkey "%s"\n' "$(capsule_key)"
	printf '\n'
	printf '\troot "/%s.kyriakon.net/gemini"\n' "$account"
	printf '\n'
	printf '\tlocation "/.git/*" {\n'
	printf '\t\tblock\n'
	printf '\t}\n'
	printf '}\n'
}

# write_group_conf: the file, rewritten only when it would differ.
write_group_conf() {
	typeset target candidate
	target=$(group_conf)
	candidate="$target.new.$$"
	if ! group_conf_body > "$candidate"; then
		rm -f "$candidate"
		exit 1
	fi
	if [ -f "$target" ] && cmp -s "$candidate" "$target"; then
		rm -f "$candidate"
		conf_changed=no
		printf '%s: unchanged\n' "$target"
		return 0
	fi
	chmod 0644 "$candidate"
	mv "$candidate" "$target"
	conf_changed=yes
	printf 'wrote %s: %s on 1965 from %s\n' "$target" "$domain" "$(capsule_cert)"
}

assert_group_conf() {
	typeset target shape
	target=$(group_conf)
	[ -f "$target" ] || die "$target is not there after writing it"
	shape=$(stat -f '%Su:%Sg %Lp' "$target")
	[ "$shape" = "$conf_owner 644" ] || die "$target is $shape, wanted $conf_owner 644"
}

# The tree the block's root names, built by scripts/provision-member.sh.
assert_site_tree() {
	typeset public
	public=$(site_public)
	[ -d "$public" ] || die "no $public: run scripts/provision-member.sh $account first"
	[ -d "$public/gemini" ] || die "no $public/gemini: run scripts/provision-member.sh $account first"
}

# --- self-test ---------------------------------------------------------------
#
# The block and the pair are the whole risk, so both are exercised against a
# throwaway tree with the real openssl: the block's shape, a second run that
# changes nothing, a pair that carries the domain, an end-entity constraint and
# about ten years, and half a pair rebuilt. Runs as anyone, writes only under
# TMPDIR.

self_test() {
	# shellcheck disable=SC1091 # resolves at runtime from this script's directory
	. "$(dirname "$0")/lib.sh"
	typeset tree conf before out code
	self_test_begin
	# shellcheck disable=SC2154 # set by self_test_begin in lib.sh
	tree=$self_test_work

	gmid_d="$tree/etc/gmid.d"
	ssl_dir="$tree/etc/ssl"
	ssl_private="$ssl_dir/private"
	public_root="$tree/home/www"
	domain=parish.example
	account=parish-secretary
	install -d -m 0755 "$gmid_d" "$ssl_private" "$public_root/parish-secretary.kyriakon.net/gemini"
	conf_owner="$(id -un):$(stat -f '%Sg' "$gmid_d")"
	conf=$(group_conf)

	# 1. the block
	write_group_conf >/dev/null
	check "the server is the body's domain" "$(awk 'NR == 1' "$conf")" 'server "parish.example" {'
	check "it listens on the gemini port" "$(grep -c 'listen on \* port 1965' "$conf")" 1
	check "it names the domain's capsule certificate" \
		"$(grep -cF "cert \"$ssl_dir/capsule-parish.example.crt\"" "$conf")" 1
	check "and its key" \
		"$(grep -cF "key \"$ssl_private/capsule-parish.example.key\"" "$conf")" 1
	check "the root is the site owner's gemini tree" \
		"$(grep -c 'root "/parish-secretary.kyriakon.net/gemini"' "$conf")" 1
	check ".git is blocked" "$(grep -c 'location "/.git/\*"' "$conf")" 1
	check "one server block exactly" "$(grep -c '^server ' "$conf")" 1
	check "the file is mode 644 and the writer's" "$(stat -f '%Su:%Sg %Lp' "$conf")" "$conf_owner 644"
	assert_group_conf
	printf '\n%s:\n' "$conf"
	cat "$conf"
	printf '\n'

	# 2. the same again: nothing rewritten
	before=$(stat -f '%i %m' "$conf")
	write_group_conf > "$tree/again.out"
	check "a second run leaves the file alone" "$(stat -f '%i %m' "$conf")" "$before"
	check "and says so" "$(grep -c ': unchanged$' "$tree/again.out")" 1

	# 3. the pair, generated once by the script itself
	check "there is no pair to begin with" "$(pair_present && echo yes || echo no)" no
	out=$(ensure_capsule_pair)
	check "the pair exists afterwards" "$(pair_present && echo yes || echo no)" yes
	check "the key is mode 0600" "$(stat -f '%Lp' "$(capsule_key)")" 600
	check "the certificate is mode 0644" "$(stat -f '%Lp' "$(capsule_cert)")" 644
	check "it carries the domain" \
		"$("$openssl" x509 -in "$(capsule_cert)" -noout -text | grep -cF 'DNS:parish.example')" 1
	check "it is an end entity, critically" \
		"$("$openssl" x509 -in "$(capsule_cert)" -noout -text | grep -A1 'Basic Constraints' | grep -cF 'critical')" 1
	check "and it says CA:FALSE" \
		"$("$openssl" x509 -in "$(capsule_cert)" -noout -text | grep -cF 'CA:FALSE')" 1
	check "it is still valid in ten years less three days" \
		"$("$openssl" x509 -in "$(capsule_cert)" -noout -checkend $((3650 * 86400 - 3 * 86400)) >/dev/null 2>&1 && echo yes || echo no)" yes
	check "and not in ten years plus three days" \
		"$("$openssl" x509 -in "$(capsule_cert)" -noout -checkend $((3650 * 86400 + 3 * 86400)) >/dev/null 2>&1 && echo yes || echo no)" no
	check "and the run prints the fingerprint for the account page" \
		"$(printf '%s\n' "$out" | grep -c '^capsule fingerprint (account page): [0-9A-F][0-9A-F]:')" 1

	# 4. a second run does not touch the pair
	before="$(stat -f '%i %m' "$(capsule_cert)") $(stat -f '%i %m' "$(capsule_key)")"
	out=$(ensure_capsule_pair)
	check "a second run leaves the pair alone" \
		"$(stat -f '%i %m' "$(capsule_cert)") $(stat -f '%i %m' "$(capsule_key)")" "$before"
	check "and says the pair was left alone" "$(printf '%s\n' "$out" | grep -c 'left alone')" 1
	check "and prints no fingerprint" "$(printf '%s\n' "$out" | grep -c 'fingerprint')" 0

	# 5. the configuration file is stable and names the domain
	check "the configuration asks for the domain" \
		"$(grep -c '^subjectAltName		= DNS:parish.example$' "$(capsule_cnf)")" 1
	before=$(stat -f '%i %m' "$(capsule_cnf)")
	write_capsule_cnf > "$tree/cnf.out"
	check "a second run leaves the configuration alone" "$(stat -f '%i %m' "$(capsule_cnf)")" "$before"

	# 6. half a pair is regenerated, not served
	rm -f "$(capsule_key)"
	ensure_capsule_pair > "$tree/half.out" 2>&1
	check "half a pair is rebuilt" "$(pair_present && echo yes || echo no)" yes
	check "and says the account page fingerprint changed" \
		"$(grep -c 'account page publishes has to be updated' "$tree/half.out")" 1

	# 7. a site owner whose tree is not built is refused
	account=nobody
	rm -rf "$public_root/nobody.kyriakon.net"
	code=0
	( assert_site_tree ) > "$tree/notree.out" 2>&1 || code=$?
	check "a site owner with no tree is refused" "$code" 1
	check "and the refusal names provision-member.sh" \
		"$(grep -c 'scripts/provision-member.sh nobody' "$tree/notree.out")" 1

	# 8. a name that is not a validated FQDN is refused at the door
	check "a domain is accepted" "$(domain_ok parish.example && printf yes || printf no)" yes
	check "a single label is refused" "$(domain_ok parish && printf yes || printf no)" no
	check "a leading hyphen is refused" "$(domain_ok -parish.example && printf yes || printf no)" no

	self_test_end
}

conf_changed=no

case "${1:-}" in
--self-test)
	[ "$#" -eq 1 ] || usage
	self_test
	;;
"")
	usage
	;;
-*)
	usage
	;;
*)
	[ "$#" -eq 2 ] || usage
	domain="$1"
	account="$2"
	domain_ok "$domain" || die "not a domain: $domain (lowercase FQDN, at least two labels)"
	account_ok "$account" || die "not an account name: $account"
	[ "$(id -u)" -eq 0 ] || die "run this with doas: it writes $gmid_d and the pair under $ssl_dir"
	[ -x "$openssl" ] || die "no $openssl"
	[ -d "$gmid_d" ] || die "no $gmid_d: doas ksh scripts/deploy-mail.sh creates it, with the index gmid.conf includes"
	assert_site_tree
	# The pair before the block, so no block is ever written naming a certificate
	# that is not there: gmid -n in the --web pass would refuse for every body at
	# once.
	ensure_capsule_pair
	write_group_conf
	assert_group_conf
	if [ "$conf_changed" = yes ]; then
		printf 'next: doas ksh scripts/cron-apply.sh --web   # regenerate the index, check gmid, reload\n'
	fi
	;;
esac
