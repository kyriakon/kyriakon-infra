#!/bin/ksh
# provision-member-acme.sh: the member's acme-client block and its queued request.
#
# Usage:
#   doas ksh scripts/provision-member-acme.sh <username>
#        ksh scripts/provision-member-acme.sh --self-test
#
# Runs ON the box as root, after scripts/provision-member.sh has built the
# member's tree, as the third lane beside the web and capsule ones.
#
# What it writes, and why each shape:
#
#   /etc/acme-client.d/<username>.kyriakon.net.conf    root:wheel 0644
#
# One domain block, repeating every line a hand-written block in
# /etc/acme-client.conf carries. The header there states why each line is
# repeated rather than inherited from another block: challengedir is a per-domain
# option, httpd chroots to /home/www so the challenge file has to land at
# /home/www/acme, and the certificate pair is one per name. `sign with
# letsencrypt` names the authority block in the tracked file; the include is
# parsed as one configuration, so the member file does not repeat it.
#
# The file lives in the included directory rather than in the tracked top level,
# which is what keeps member names out of the daily renewal lane: renew-acme.sh
# reads the handles out of /etc/acme-client.conf itself and deliberately does not
# follow the include. The index that lists this file is regenerated by
# scripts/cron-apply.sh --web with the other two, so this script is not an index
# writer.
#
# Issuance is not immediate, and this lane does not issue anything. A new
# certificate spends the registered domain's budget of one per 202 minutes, so
# the request joins scripts/acme-queue.sh's queue and the worker spends a slot
# when one opens. Until the certificate lands the member has mail, an upload path
# and a capsule, and the httpd file has no block behind the relay; once it lands
# the queue runs the web lane and scripts/cron-apply.sh --web, which is where the
# loopback vhost, the relayd keypair and the reload come from.
#
# The request is filed on every run, not only when the file is new. acme-queue.sh
# --add is idempotent and says "already queued" for a request that is already
# there, so a member whose queue entry was lost is refiled by the next
# provisioning run, and a run over a member whose certificate is already issued
# is a queue entry that the worker closes as "already current".
#
# Writing is ordered and atomic, as the spec requires: the block is compared
# with what is there and moved into place only when the bytes differ, so a second
# run leaves the file's inode and mtime alone. The queue call comes after the
# write, so a request never names a file that is not there.
#
# The queue itself is /root/bin/acme-queue.sh, where scripts/deploy-mail.sh
# installs it and from where cron runs it. ACME_QUEUE overrides the path for the
# self-test, which files requests against a stub and never touches the live
# store.
#
# Not this script's job: the member's tree (scripts/provision-member.sh), the
# issuance (scripts/acme-queue.sh --run), the index or the reload
# (scripts/cron-apply.sh --web), or the vhost for the same name
# (scripts/provision-member-web.sh).

set -euo pipefail

# The temporary file is created under this umask, so a half-written block is
# never readable by another account even for the moment before the rename.
umask 077

script_dir=$(cd "$(dirname "$0")" && pwd)
acme_d=${ACME_D:-/etc/acme-client.d}
public_root=${PUBLIC_ROOT:-/home/www}
acme_queue=${ACME_QUEUE:-/root/bin/acme-queue.sh}
conf_owner="root:wheel"

usage() {
	cat >&2 <<'USAGE'
usage: doas ksh provision-member-acme.sh <username>
       ksh scripts/provision-member-acme.sh --self-test
USAGE
	exit 2
}

die() {
	printf 'provision-member-acme: %s\n' "$*" >&2
	exit 1
}

# The name, and the same charset rule add-user.sh and provision-member.sh apply.
# It is a subdomain label here and the stem of the generated file, so a name
# outside that set could not be a member's.
name_ok() {
	printf '%s' "$1" | grep -Eq '^[a-z0-9][a-z0-9._-]{0,31}$'
}

# The paths, as functions rather than variables so the self-test rebinds the
# directory once and every caller follows.
member_conf() { printf '%s/%s.kyriakon.net.conf' "$acme_d" "$user"; }
cert_file() { printf '/etc/ssl/%s.kyriakon.net.fullchain.pem' "$user"; }
key_file() { printf '/etc/ssl/private/%s.kyriakon.net.key' "$user"; }

# The file body, printed rather than written so the caller can compare it with
# what is already there. The comment says where it came from, because this file
# is the one member configuration a hand edit would look reasonable in.
member_conf_body() {
	printf '# %s.kyriakon.net, generated by scripts/provision-member-acme.sh.\n' "$user"
	printf '# Do not edit: the next provisioning run writes this file again.\n'
	printf 'domain %s.kyriakon.net {\n' "$user"
	printf '\tchallengedir "/home/www/acme"\n'
	printf '\tdomain key "%s"\n' "$(key_file)"
	printf '\tdomain full chain certificate "%s"\n' "$(cert_file)"
	printf '\tsign with letsencrypt\n'
	printf '}\n'
}

# write_member_conf: the file in the shape the member's name calls for. Sets
# conf_changed so the caller can say which of the two states it found.
write_member_conf() {
	typeset target candidate

	target=$(member_conf)
	candidate="$target.new.$$"
	if ! member_conf_body > "$candidate"; then
		rm -f "$candidate"
		exit 1
	fi

	# Compared before anything moves, so a run that would produce the same file
	# leaves its mtime and inode alone.
	if [ -f "$target" ] && cmp -s "$candidate" "$target"; then
		rm -f "$candidate"
		conf_changed=no
		printf '%s: unchanged\n' "$target"
		return 0
	fi

	chmod 0644 "$candidate"
	mv "$candidate" "$target"
	conf_changed=yes
	printf 'wrote %s\n' "$target"
}

# The last line of defence: the file is there, root's, and readable by
# acme-client, which parses it as root but must not read a file a member could
# have edited. The expected owner is a variable because the self-test's throwaway
# tree belongs to whoever runs the test.
assert_member_conf() {
	typeset conf shape
	conf=$(member_conf)
	[ -f "$conf" ] || die "$conf is not there after writing it"
	shape=$(stat -f '%Su:%Sg %Lp' "$conf")
	[ "$shape" = "$conf_owner 644" ] || die "$conf is $shape, wanted $conf_owner 644"
}

# The tree provision-member.sh builds, which is what the vhost will serve. A
# member file for a name with no tree is an order for a site with nowhere to put
# it, so this is a refusal rather than a note.
assert_member_tree() {
	typeset public
	public="$public_root/$user.kyriakon.net"
	[ -d "$public" ] || die "no $public: run scripts/provision-member.sh $user first"
}

# File the request with the queue. Idempotent in the queue itself, so this runs
# on every provisioning pass rather than only on the one that wrote the file.
queue_request() {
	[ -f "$acme_queue" ] || die "no $acme_queue: scripts/deploy-mail.sh installs the certificate queue there, and nothing is issued without it"
	ksh "$acme_queue" --add "$user.kyriakon.net"
}

# --- self-test ---------------------------------------------------------------
#
# The block's shape, its idempotency and the queue call are the whole of this
# script's risk, so they are exercised against a throwaway tree with the queue
# stubbed. Runs as anyone, writes only under TMPDIR.

self_test() {
	# shellcheck disable=SC1091 # resolves at runtime from this script's directory
	. "$script_dir/lib.sh"
	typeset tree conf before code calls
	self_test_begin
	# shellcheck disable=SC2154 # set by self_test_begin in lib.sh
	tree=$self_test_work

	acme_d="$tree/etc/acme-client.d"
	public_root="$tree/home/www"
	install -d -m 0755 "$acme_d" "$public_root/alice.kyriakon.net"
	conf_owner="$(id -un):$(stat -f '%Sg' "$acme_d")"
	user=alice

	# The queue is stubbed, so the test records the call instead of writing the
	# live store the root-only worker reads.
	calls="$tree/queue.calls"
	mkdir -p "$tree/bin"
	{
		printf '#!/bin/sh\n'
		printf 'printf "%%s\\n" "$*" >> %s\n' "'$calls'"
		printf 'printf "%%s\\n" "$*"\n'
	} > "$tree/bin/acme-queue.sh"
	chmod 0755 "$tree/bin/acme-queue.sh"
	acme_queue="$tree/bin/acme-queue.sh"

	conf=$(member_conf)

	# 1. the block, line for line
	write_member_conf > "$tree/first.out"
	check "the block names the member's domain" "$(awk 'NR == 3' "$conf")" 'domain alice.kyriakon.net {'
	check "the challenge directory is the httpd one" \
		"$(grep -c 'challengedir "/home/www/acme"' "$conf")" 1
	check "the domain key is the pair's private half" \
		"$(grep -c 'domain key "/etc/ssl/private/alice.kyriakon.net.key"' "$conf")" 1
	check "the full chain is the acme-client name relayd links from" \
		"$(grep -c 'domain full chain certificate "/etc/ssl/alice.kyriakon.net.fullchain.pem"' "$conf")" 1
	check "the authority is the tracked one" \
		"$(grep -c 'sign with letsencrypt' "$conf")" 1
	check "and there is one block, not two" "$(grep -c '^domain ' "$conf")" 1
	check "the file is mode 644 and the writer's" "$(stat -f '%Su:%Sg %Lp' "$conf")" "$conf_owner 644"
	assert_member_conf
	printf '\n%s:\n' "$conf"
	cat "$conf"
	printf '\n'

	# 2. a second run leaves the file alone and still files the request
	before=$(stat -f '%i %m' "$conf")
	write_member_conf > "$tree/again.out"
	check "a second run leaves the file alone" "$(stat -f '%i %m' "$conf")" "$before"
	check "and says the file is unchanged" "$(grep -c 'unchanged' "$tree/again.out")" 1
	queue_request > "$tree/queued.out"
	check "the request names the member's hostname" "$(cat "$calls")" "--add alice.kyriakon.net"
	check "and the queue's own words are passed through" "$(grep -c -- '--add alice.kyriakon.net' "$tree/queued.out")" 1

	# 3. a member whose tree was never built is refused before anything is queued
	user=bob
	code=0
	( assert_member_tree ) > "$tree/notree.out" 2>&1 || code=$?
	check "a member with no tree is refused" "$code" 1
	check "and the refusal names provision-member.sh" \
		"$(grep -c 'scripts/provision-member.sh bob' "$tree/notree.out")" 1

	# 4. a name that is not a member name is refused at the door
	check "a name outside the charset is refused" \
		"$(name_ok 'Alice' && printf yes || printf no)" "no"
	check "a path is refused" "$(name_ok '../alice' && printf yes || printf no)" "no"

	# 5. a missing queue is a refusal, not a silent file with no request
	acme_queue="$tree/bin/missing.sh"
	code=0
	( queue_request ) > "$tree/noqueue.out" 2>&1 || code=$?
	check "a missing queue is refused" "$code" 1
	check "and names the deploy that installs it" \
		"$(grep -c 'scripts/deploy-mail.sh' "$tree/noqueue.out")" 1
	check "and nothing was queued for it" "$(wc -l < "$calls" | tr -d ' ')" 1

	self_test_end
}

conf_changed=no

case "${1:-}" in
--self-test)
	[ "$#" -eq 1 ] || usage
	self_test
	;;
"")
	usage
	;;
-*)
	usage
	;;
*)
	[ "$#" -eq 1 ] || usage
	user="$1"
	name_ok "$user" || die "not a member name: $user (lowercase [a-z0-9._-], first character alphanumeric, at most 32 characters)"
	[ "$(id -u)" -eq 0 ] || die "run this with doas: it writes $acme_d and files a root-only queue request"
	# deploy-mail.sh creates the directory with the empty index acme-client.conf
	# includes. A member block with no index to list it is a config acme-client
	# never reads, and a box that has not run the mail deploy has no member
	# certificates at all.
	[ -d "$acme_d" ] || die "no $acme_d: doas ksh scripts/deploy-mail.sh creates it, with the index acme-client.conf includes"
	assert_member_tree
	write_member_conf
	assert_member_conf
	queue_request
	if [ "$conf_changed" = yes ]; then
		printf 'next: doas ksh scripts/cron-apply.sh --web   # list the block, then the queue issues it\n'
	fi
	;;
esac
