#!/bin/ksh
# provision-group-acme.sh: an own-domain body's acme-client block and queued order.
#
# Usage:
#   doas ksh scripts/provision-group-acme.sh <domain> <site-account>
#        ksh scripts/provision-group-acme.sh --self-test
#
# Runs ON the box as root, from the drain's group intent, as the third lane beside
# the web and capsule ones.
#
# What it writes, and why each shape:
#
#   /etc/acme-client.d/<domain>.conf    root:wheel 0644
#
# One order for the domain and www. The certificate is issued over HTTP-01 against
# the body's own name pointed at the box, so the body's A and AAAA records have to
# be live first and the port 80 vhosts from scripts/provision-group-web.sh serve
# the challenge. The block repeats every line a hand-written block in
# /etc/acme-client.conf carries, because the include is parsed as one
# configuration and nothing is inherited: challengedir is per-domain and httpd
# chroots to /home/www, so the challenge file has to land at /home/www/acme, and
# the certificate pair is one per name.
#
# The file lives in the included directory rather than the tracked top level, so
# the body's name never becomes a hand-maintained line. scripts/renew-acme.sh
# reads the same generated files, so a renewal is the daily lane's rather than
# the queue's, which is what keeps a domain certificate from lapsing ninety days
# after approval.
#
# The order joins scripts/acme-queue.sh rather than issuing here. A new
# certificate spends the registered domain's budget, one every 202 minutes, and
# the queue works oldest first: one global attempt slot at a time. The body's
# domain is its own registered domain, so this order spends one slot of the
# body's fifty, not kyriakon.net's; the queue's global spacing still applies, so
# it waits behind earlier requests in the same queue. The site owner's account is
# recorded with the request because the queue needs it to write the 443 vhost when
# the certificate lands.
#
# The request is filed on every run, not only when the file is new. acme-queue.sh
# --add is idempotent and says "already queued" for a request that is already
# there, so a lost queue entry is refiled by the next provisioning run.
#
# Writing is ordered and atomic: the block is compared with what is there and
# moved into place only when the bytes differ. The queue call comes after the
# write, so a request never names a file that is not there.
#
# Env: none. The self-test rebinds this script's paths and points ACME_QUEUE at a
# stub, so it needs no root and touches nothing outside its tree.
#
# Not this script's job: the site owner's tree (scripts/provision-member.sh), the
# vhosts (scripts/provision-group-web.sh), the capsule
# (scripts/provision-group-capsule.sh), issuance (scripts/acme-queue.sh --run),
# or the index and reload (scripts/cron-apply.sh --web).

set -euo pipefail

# The temporary file is created under this umask, so a half-written block is never
# readable by another account even before the rename.
umask 077

script_dir=$(cd "$(dirname "$0")" && pwd)
acme_d=${ACME_D:-/etc/acme-client.d}
public_root=${PUBLIC_ROOT:-/home/www}
acme_queue=${ACME_QUEUE:-/root/bin/acme-queue.sh}
conf_owner="root:wheel"

usage() {
	cat >&2 <<'USAGE'
usage: doas ksh provision-group-acme.sh <domain> <site-account>
       ksh provision-group-acme.sh --self-test
USAGE
	exit 2
}

die() {
	printf 'provision-group-acme: %s\n' "$*" >&2
	exit 1
}

# A validated FQDN: labels of lowercase letters, digits and hyphens, at least two
# of them, and no label starting or ending with a hyphen.
domain_ok() {
	typeset name="$1"
	[ "${#name}" -le 253 ] || return 1
	case "$name" in
	*.*) ;;
	*) return 1 ;;
	esac
	printf '%s' "$name" | grep -Eq '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$'
}

# The site owner is a member account: the same charset add-user.sh applies.
account_ok() {
	printf '%s' "$1" | grep -Eq '^[a-z0-9][a-z0-9._-]{0,31}$'
}

# The paths, as functions so the self-test rebinds the directory once.
group_conf() { printf '%s/%s.conf' "$acme_d" "$domain"; }
cert_file() { printf '/etc/ssl/%s.fullchain.pem' "$domain"; }
key_file() { printf '/etc/ssl/private/%s.key' "$domain"; }
site_public() { printf '%s/%s.kyriakon.net' "$public_root" "$account"; }

# The file body. The comment says where it came from, because this is the one
# generated file a hand edit would look reasonable in.
group_conf_body() {
	printf '# %s, generated by scripts/provision-group-acme.sh.\n' "$domain"
	printf '# Do not edit: the next provisioning run writes this file again.\n'
	printf 'domain %s {\n' "$domain"
	printf '\talternative names {\n'
	printf '\t\twww.%s\n' "$domain"
	printf '\t}\n'
	printf '\tchallengedir "/home/www/acme"\n'
	printf '\tdomain key "%s"\n' "$(key_file)"
	printf '\tdomain full chain certificate "%s"\n' "$(cert_file)"
	printf '\tsign with letsencrypt\n'
	printf '}\n'
}

# write_group_conf: the file in the shape the domain's order calls for. Sets
# conf_changed so the caller can say which state it found.
write_group_conf() {
	typeset target candidate

	target=$(group_conf)
	candidate="$target.new.$$"
	if ! group_conf_body > "$candidate"; then
		rm -f "$candidate"
		exit 1
	fi

	if [ -f "$target" ] && cmp -s "$candidate" "$target"; then
		rm -f "$candidate"
		conf_changed=no
		printf '%s: unchanged\n' "$target"
		return 0
	fi

	chmod 0644 "$candidate"
	mv "$candidate" "$target"
	conf_changed=yes
	printf 'wrote %s\n' "$target"
}

# The last line of defence: the file is there, root's, and readable by
# acme-client, which parses it as root but must not read a file a body could have
# edited. The expected owner is a variable because the self-test's tree belongs
# to whoever runs the test.
assert_group_conf() {
	typeset conf shape
	conf=$(group_conf)
	[ -f "$conf" ] || die "$conf is not there after writing it"
	shape=$(stat -f '%Su:%Sg %Lp' "$conf")
	[ "$shape" = "$conf_owner 644" ] || die "$conf is $shape, wanted $conf_owner 644"
}

# The site owner's tree. An order for a name with no tree is a certificate for a
# site with nowhere to put it, so this is a refusal rather than a note.
assert_site_tree() {
	typeset public
	public=$(site_public)
	[ -d "$public" ] || die "no $public: run scripts/provision-member.sh $account first"
}

# File the request with the queue, recording the account the web lane will need
# when the certificate lands. Idempotent in the queue itself.
queue_request() {
	[ -f "$acme_queue" ] || die "no $acme_queue: scripts/deploy-mail.sh installs the certificate queue there, and nothing is issued without it"
	ksh "$acme_queue" --add "$domain" "$account"
}

# --- self-test ---------------------------------------------------------------
#
# The block, its idempotency and the queue call are the whole risk, so they are
# exercised against a throwaway tree with the queue stubbed. Runs as anyone,
# writes only under TMPDIR.

self_test() {
	# shellcheck disable=SC1091 # resolves at runtime from this script's directory
	. "$script_dir/lib.sh"
	typeset tree conf before code calls
	self_test_begin
	# shellcheck disable=SC2154 # set by self_test_begin in lib.sh
	tree=$self_test_work

	acme_d="$tree/etc/acme-client.d"
	public_root="$tree/home/www"
	install -d -m 0755 "$acme_d" "$public_root/parish-secretary.kyriakon.net"
	conf_owner="$(id -un):$(stat -f '%Sg' "$acme_d")"
	domain=parish.example
	account=parish-secretary

	calls="$tree/queue.calls"
	mkdir -p "$tree/bin"
	{
		printf '#!/bin/sh\n'
		printf 'printf "%%s\\n" "$*" >> %s\n' "'$calls'"
		printf 'printf "%%s\\n" "$*"\n'
	} > "$tree/bin/acme-queue.sh"
	chmod 0755 "$tree/bin/acme-queue.sh"
	acme_queue="$tree/bin/acme-queue.sh"

	conf=$(group_conf)

	# 1. the block, line for line
	write_group_conf > "$tree/first.out"
	check "the block names the body's domain" "$(awk 'NR == 3' "$conf")" 'domain parish.example {'
	check "the order covers www as an alternative name" \
		"$(awk '/alternative names/,/}/' "$conf" | grep -c 'www.parish.example')" 1
	check "the challenge directory is the httpd one" \
		"$(grep -c 'challengedir "/home/www/acme"' "$conf")" 1
	check "the domain key is the pair's private half" \
		"$(grep -c 'domain key "/etc/ssl/private/parish.example.key"' "$conf")" 1
	check "the full chain is the name relayd links from" \
		"$(grep -c 'domain full chain certificate "/etc/ssl/parish.example.fullchain.pem"' "$conf")" 1
	check "the authority is the tracked one" "$(grep -c 'sign with letsencrypt' "$conf")" 1
	check "and there is one block, not two" "$(grep -c '^domain ' "$conf")" 1
	check "the file is mode 644 and the writer's" "$(stat -f '%Su:%Sg %Lp' "$conf")" "$conf_owner 644"
	assert_group_conf
	printf '\n%s:\n' "$conf"
	cat "$conf"
	printf '\n'

	# 2. a second run leaves the file alone and still files the request
	before=$(stat -f '%i %m' "$conf")
	write_group_conf > "$tree/again.out"
	check "a second run leaves the file alone" "$(stat -f '%i %m' "$conf")" "$before"
	check "and says the file is unchanged" "$(grep -c 'unchanged' "$tree/again.out")" 1
	queue_request > "$tree/queued.out"
	check "the request names the domain and its site owner" \
		"$(cat "$calls")" "--add parish.example parish-secretary"
	check "and the queue's own words are passed through" \
		"$(grep -c -- '--add parish.example parish-secretary' "$tree/queued.out")" 1

	# 3. a site owner whose tree was never built is refused before anything is
	# queued
	account=parish-warden
	code=0
	( assert_site_tree ) > "$tree/notree.out" 2>&1 || code=$?
	check "a site owner with no tree is refused" "$code" 1
	check "and the refusal names provision-member.sh" \
		"$(grep -c 'scripts/provision-member.sh parish-warden' "$tree/notree.out")" 1

	# 4. a name that is not a validated FQDN is refused at the door
	check "a domain is accepted" "$(domain_ok parish.example && printf yes || printf no)" yes
	check "a single label is refused" "$(domain_ok parish && printf yes || printf no)" no
	check "a path is refused" "$(domain_ok ../parish.example && printf yes || printf no)" no

	# 5. a missing queue is a refusal, not a silent file with no request
	acme_queue="$tree/bin/missing.sh"
	code=0
	( queue_request ) > "$tree/noqueue.out" 2>&1 || code=$?
	check "a missing queue is refused" "$code" 1
	check "and names the deploy that installs it" \
		"$(grep -c 'scripts/deploy-mail.sh' "$tree/noqueue.out")" 1
	check "and nothing was queued for it" "$(wc -l < "$calls" | tr -d ' ')" 1

	self_test_end
}

conf_changed=no

case "${1:-}" in
--self-test)
	[ "$#" -eq 1 ] || usage
	self_test
	;;
"")
	usage
	;;
-*)
	usage
	;;
*)
	[ "$#" -eq 2 ] || usage
	domain="$1"
	account="$2"
	domain_ok "$domain" || die "not a domain: $domain (lowercase FQDN, at least two labels)"
	account_ok "$account" || die "not an account name: $account"
	[ "$(id -u)" -eq 0 ] || die "run this with doas: it writes $acme_d and files a root-only queue request"
	[ -d "$acme_d" ] || die "no $acme_d: doas ksh scripts/deploy-mail.sh creates it, with the index acme-client.conf includes"
	assert_site_tree
	write_group_conf
	assert_group_conf
	queue_request
	if [ "$conf_changed" = yes ]; then
		printf 'next: doas ksh scripts/cron-apply.sh --web   # list the block, then the queue issues it\n'
	fi
	;;
esac
