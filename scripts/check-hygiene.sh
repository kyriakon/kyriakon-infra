#!/bin/ksh
# check-hygiene.sh — two questions about a box, answered with the noise filtered.
#
#   doas ksh scripts/check-hygiene.sh
#
# 1. Permission and ownership drift against mtree's whole-system spec.
#    `/etc/mtree/special` covers /etc, /root, /usr and /var, and is root-only, so
#    both `-f` and `-p /` are needed: the spec's paths are rooted at /, and passing
#    `-p /etc` makes every spec path report as missing and every real file as
#    extra, which is a very long list that means nothing. Even run correctly,
#    mtree calls every file it does not already know about `extra`, and on a box
#    with a mail stack that is most of /etc. The differences worth reading are
#    mode, uid, gid, type, size and link, so those are the only ones printed.
#
#    The daily security(8) mail runs the same comparison, which is the automatic
#    version of this. This is the one to run when you want the answer now.
#
# 2. Whether this box's address is on the blocklists, and which list said so.
#    Spamhaus Zen refuses shared resolvers, and every resolver a Hetzner box is
#    handed is one, so it answers 127.255.255.254 to this box and to a public
#    resolver alike. That is a refusal rather than a listing: a listing is 127.0.0.x
#    and its last octet names the matching list. So the check asks a list of zones,
#    takes the first that gives a verdict, and names it, because a clean answer from
#    SpamCop is a fact about SpamCop and not about Spamhaus. Both this and
#    abuse-monitor.sh go through dnsbl_verdict in lib.sh, so they cannot drift.
#
# 3. Whether a cron job can reach the tools the cron jobs need. cron(8) hands
#    jobs PATH=/usr/bin:/bin, packages live in /usr/local and ifconfig in /sbin,
#    so a job whose PATH is not restored finds neither. abuse-monitor.sh's
#    Healthchecks ping is `curl ... || true`, which makes that look like a clean
#    run: the box reads as monitored while nothing is sent. This section sources
#    /root/.kyriakon-env on cron's PATH and asks what a job would find.
#
# 4. Whether the finger service is intact. It is served by fingerd under inetd
#    from a generated page, so the failure worth catching is a half-configured
#    one: a page carrying no endpoints, a missing provider, or an inetd line that
#    was never added. Each of those leaves port 79 either dark or answering with
#    the wrong thing, and none of them is visible from the box being up. The page
#    is regenerated by every mail deploy, so a stale list only follows a hand edit
#    to httpd.conf or gmid.conf.
#
# 5. Whether the deployed service catalogue matches the tracked one, which is
#    check-keyring-drift.sh's own precedent of comparing a published file against
#    the box's copy. The catalogue is one file the three front-ends read, so a
#    box running a different one is three renderings nobody reviewed.
#
# 6. Whether the terraform root still refuses to remove the mail box, and whether
#    the weekly restore test still has an image to create from.
#
# 7. Whether the two files that name the mail domains agree. smtpd accepts mail
#    for every domain in /etc/mail/mail_domains, and spamd traps any destination
#    whose domain is not in /etc/mail/spamd.alloweddomains: trapping is not
#    greylisting, it puts the sending host on the blocklist. The two files are
#    written by different steps, and only the first is generated, so this is the
#    pair that goes out of step when a body's own domain is added.
#
# Read-only. Exits non-zero when something is wrong, so cron could run it, though
# the daily mail already covers the permissions half.
#
#   ksh scripts/check-hygiene.sh --self-test   the checks that run on fixtures:
#                                              sections 7, 8, 9 and 10, and
#                                              section 3's remedy lines

set -euo pipefail

# cron(8) jobs are given PATH=/usr/bin:/bin, and packages live in /usr/local while
# ifconfig lives in /sbin. Whether this file is run by hand or by cron, put them
# back, for the reason section 3 exists.
PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/sbin:$PATH"
export PATH

script_dir="$(dirname "$0")"
if [ ! -f "$script_dir/lib.sh" ]; then
	printf '%s: lib.sh is not in %s. Install the two files together, as lib.sh describes.\n' \
		"$0" "$script_dir" >&2
	exit 1
fi

# shellcheck disable=SC1091 # lib.sh resolves at runtime from this script's dir
. "$script_dir/lib.sh"

status=0

# domains_missing_from <mail-domains-file> <allowed-file>
#
# Print, one per line, every domain the first file names that the second has no
# bare `@domain` line for. The first file's comments and blank lines are skipped,
# because it explains itself; the allow list is matched whole-line, because that
# is how spamd reads it, so a line carrying anything else does not count and a
# domain on one is reported. The comparison runs in this direction only: a line
# for a domain smtpd does not accept passes mail that never arrives, and traps
# nothing, so it is not a finding.
domains_missing_from() {
	typeset list="$1" allowed="$2" line
	# The `|| [ -n "$line" ]` is not decoration: `read` returns false at end of
	# input, so a final line with no trailing newline never reaches the body, and
	# the domain a hand edit appended last is the one most likely to be the one
	# missing from the allow list.
	while read -r line || [ -n "$line" ]; do
		line=$(printf '%s' "$line" | sed -e 's/#.*//' -e 's/[[:space:]]//g')
		[ -n "$line" ] || continue
		grep -qxF "@$line" "$allowed" || printf '%s\n' "$line"
	done < "$list"
}

# tool_remedy <tool>... — one line of remedy per tool cron could not find.
#
# Takes the absent list rather than reading a loop variable: a caller's `tool`
# after its own loop is whichever tool it looked at last, which is how a box
# missing only hcloud was told to install jq, while a box missing only curl was
# told nothing at all.
tool_remedy() {
	typeset tool
	for tool in "$@"; do
		case "$tool" in
		# curl is a package here: base has ftp(1), and setup-env.sh lists curl
		# among the tools cron cannot find without the PATH line.
		hcloud|jq|curl) printf '  %s is a package: doas pkg_add %s\n' "$tool" "$tool" ;;
		ifconfig) printf '  %s ships in base: the PATH line above is what it needs\n' "$tool" ;;
		*) printf '  %s: check the PATH line above, then whether it is installed\n' "$tool" ;;
		esac
	done
}

# alert_address_problem <env-file> <mail-domains-file>
#
# Why the address notify_operator mails is not usable, one line, or nothing. It
# matters more than it reads: an address that cannot receive does not fail the
# alert, it demotes it. notify_operator prints instead, cron mails the print, and
# the mail arrives under cron's own subject with the component and the event gone
# from the one field an operator triages on.
#
# The file is sourced rather than parsed, because that is how the cron lines and
# lib.sh read it, and a value this cannot see is a value they cannot see either.
alert_address_problem() {
	typeset env_file="$1" domains="$2" value domain
	value=$(env -i PATH=/usr/bin:/bin:/usr/local/bin sh -c \
		". '$env_file'; printf '%s' \"\${ALERT_EMAIL:-}\"" 2>/dev/null) || value=''
	case "$value" in
	"")
		printf 'ALERT_EMAIL is not set in %s, so every alert falls back to printing and cron mails it under its own subject\n' \
			"$env_file"
		return 0
		;;
	*REPLACE_ME*)
		printf 'ALERT_EMAIL in %s is still the template placeholder (%s), so nothing can be mailed to it\n' \
			"$env_file" "$value"
		return 0
		;;
	*@*) ;;
	*)
		printf 'ALERT_EMAIL in %s is not an address: %s\n' "$env_file" "$value"
		return 0
		;;
	esac
	domain=${value##*@}
	if [ -f "$domains" ] && grep -qxF "$domain" "$domains"; then
		printf 'ALERT_EMAIL is %s, and this box accepts mail for %s: a mail box cannot report its own mail being broken\n' \
			"$value" "$domain"
	fi
}

# deployed_drift <checkout-scripts> <dir>...
#
# One line per installed file whose copy is not the checkout's, and per directory
# that is gone. A script the checkout has and the box does not install is not a
# finding: the deploys name what they install, and this compares the copies that
# exist.
deployed_drift() {
	typeset checkout="$1" dir file name
	shift
	for dir in "$@"; do
		if [ ! -d "$dir" ]; then
			printf '%s: the directory is gone\n' "$dir"
			continue
		fi
		for file in "$dir"/*.sh; do
			[ -f "$file" ] || continue
			name=$(basename "$file")
			if [ ! -f "$checkout/$name" ]; then
				printf '%s: not in the checkout\n' "$file"
				continue
			fi
			cmp -s "$file" "$checkout/$name" \
				|| printf '%s differs from %s\n' "$file" "$checkout/$name"
		done
	done
}

# store_drift <store-dir> <owner>
#
# Every file under the store directory that the owner does not own. The handler
# renders the status pages from these files and runs unprivileged, so a record it
# cannot read is a page that answers as an unknown token.
store_drift() {
	if [ ! -d "$1" ]; then
		printf '%s: the directory is gone\n' "$1"
		return
	fi
	find "$1" -type f ! -user "$2" -print
}

# The comparison above, the remedy lines and the address check below, against
# fixtures, so a change to any of them is not a claim. All three drive a function
# and not the box, which is why this can run anywhere.
self_test() {
	typeset dir out want
	dir=$(mktemp -d "${TMPDIR:-/tmp}/check-hygiene-test.XXXXXX") || exit 1
	# The value is interpolated rather than referenced, so the trap does not read
	# a name this function scoped and set -u would then refuse.
	# shellcheck disable=SC2064
	trap "rm -rf '$dir'" EXIT

	printf 'kyriakon.net\nparish.example\nschool.example\n' > "$dir/mail_domains"
	printf '# the platform domain, and nothing else yet\n@kyriakon.net\n' > "$dir/allowed"
	want=$(printf 'parish.example\nschool.example')
	out=$(domains_missing_from "$dir/mail_domains" "$dir/allowed")
	[ "$out" = "$want" ] || {
		printf 'FAIL: a domain smtpd accepts and spamd does not; expected [%s], got [%s]\n' \
			"$want" "$out" >&2
		exit 1
	}

	printf '@kyriakon.net\n@parish.example\n@school.example\n' > "$dir/allowed"
	out=$(domains_missing_from "$dir/mail_domains" "$dir/allowed")
	[ -z "$out" ] || {
		printf 'FAIL: expected nothing, got [%s]\n' "$out" >&2
		exit 1
	}

	# An extra line in the allow list is not a finding, and a comment is not a
	# domain.
	printf 'kyriakon.net\n# parish.example, added by hand\n' > "$dir/mail_domains"
	out=$(domains_missing_from "$dir/mail_domains" "$dir/allowed")
	[ -z "$out" ] || {
		printf 'FAIL: an extra line and a comment are not findings; got [%s]\n' "$out" >&2
		exit 1
	}

	# A last line with no trailing newline still counts. `read` does not run its
	# body for one, and a hand edit that appends a domain without ending the line
	# is the likeliest way for the pair to go out of step.
	printf '@kyriakon.net\n' > "$dir/allowed"
	printf 'kyriakon.net\nschool.example' > "$dir/mail_domains"
	out=$(domains_missing_from "$dir/mail_domains" "$dir/allowed")
	[ "$out" = "school.example" ] || {
		printf 'FAIL: a last line with no trailing newline; expected [school.example], got [%s]\n' \
			"$out" >&2
		exit 1
	}

	# The remedy is per tool, from the absent list. The caller used to print one
	# line using `$tool`, which after its loop is jq whatever is missing.
	out=$(tool_remedy hcloud)
	[ "$out" = '  hcloud is a package: doas pkg_add hcloud' ] || {
		printf 'FAIL: the remedy for hcloud names hcloud; got [%s]\n' "$out" >&2
		exit 1
	}
	out=$(tool_remedy curl)
	[ "$out" = '  curl is a package: doas pkg_add curl' ] || {
		printf 'FAIL: curl is a package, and the remedy must say so; got [%s]\n' "$out" >&2
		exit 1
	}
	out=$(tool_remedy ifconfig)
	case "$out" in
	*pkg_add*)
		printf 'FAIL: ifconfig ships in base; got [%s]\n' "$out" >&2
		exit 1
		;;
	esac
	# Both packages get a line, the base tool gets none. The tools are separate
	# words here because that is how the caller passes the list the loop built.
	out=$(tool_remedy ifconfig hcloud jq)
	[ "$(printf '%s\n' "$out" | grep -c pkg_add)" -eq 2 ] || {
		printf 'FAIL: two absent packages are two remedies; got [%s]\n' "$out" >&2
		exit 1
	}

	# Section 8: an address that cannot receive is a silent demotion rather than
	# an error, so each way it goes wrong has to be named.
	printf 'kyriakon.net\nparish.example\n' > "$dir/domains"
	printf "export ALERT_EMAIL='REPLACE_ME_OFF_BOX_ADDRESS'\n" > "$dir/env"
	out=$(alert_address_problem "$dir/env" "$dir/domains")
	case "$out" in
	*placeholder*)
		;;
	*)
		printf 'FAIL: the template placeholder is a finding; got [%s]\n' "$out" >&2
		exit 1
		;;
	esac

	printf "export ALERT_EMAIL='ops@kyriakon.net'\n" > "$dir/env"
	out=$(alert_address_problem "$dir/env" "$dir/domains")
	case "$out" in
	*'this box accepts mail for kyriakon.net'*)
		;;
	*)
		printf 'FAIL: an address this box hosts is a finding; got [%s]\n' "$out" >&2
		exit 1
		;;
	esac

	printf "export ALERT_EMAIL='ops@example.org'\n" > "$dir/env"
	out=$(alert_address_problem "$dir/env" "$dir/domains")
	[ -z "$out" ] || {
		printf 'FAIL: an off-box address is not a finding; got [%s]\n' "$out" >&2
		exit 1
	}

	printf 'export HEALTHCHECKS_URL=example\n' > "$dir/env"
	out=$(alert_address_problem "$dir/env" "$dir/domains")
	case "$out" in
	*'not set'*)
		;;
	*)
		printf 'FAIL: an unset address is a finding; got [%s]\n' "$out" >&2
		exit 1
		;;
	esac

	# Sections 9 and 10, against fixtures rather than the box.
	mkdir -p "$dir/checkout" "$dir/deployed" "$dir/store"
	printf 'same\n' > "$dir/checkout/one.sh"
	printf 'same\n' > "$dir/deployed/one.sh"
	printf 'old\n' > "$dir/deployed/two.sh"
	printf 'new\n' > "$dir/checkout/two.sh"
	out=$(deployed_drift "$dir/checkout" "$dir/deployed")
	case "$out" in
	*two.sh*) ;;
	*) printf 'FAIL: a copy older than the checkout is a finding; got [%s]\n' "$out" >&2; exit 1 ;;
	esac
	case "$out" in
	*one.sh*) printf 'FAIL: a matching copy is not a finding; got [%s]\n' "$out" >&2; exit 1 ;;
	esac
	out=$(deployed_drift "$dir/checkout" "$dir/gone")
	case "$out" in
	*gone*) ;;
	*) printf 'FAIL: a missing directory is a finding; got [%s]\n' "$out" >&2; exit 1 ;;
	esac

	printf 'mine\n' > "$dir/store/record.json"
	[ -z "$(store_drift "$dir/store" "$(id -un)")" ] || {
		printf 'FAIL: a record owned by the running user is not a finding\n' >&2
		exit 1
	}
	other=nobody
	if [ "$(id -un)" = nobody ]; then other=root; fi
	out=$(store_drift "$dir/store" "$other")
	case "$out" in
	*record.json*) ;;
	*) printf 'FAIL: a record the owner cannot be is a finding; got [%s]\n' "$out" >&2; exit 1 ;;
	esac

	printf 'check-hygiene: self-test passed\n'
}

case "${1:-}" in
--self-test)
	self_test
	exit 0
	;;
"") ;;
*)
	printf 'usage: check-hygiene.sh [--self-test]\n' >&2
	exit 2
	;;
esac

# The box's checkout of this repository, which two sections read: the deployed
# catalogue is compared against it, and the live terraform root is read from it.
# A variable rather than a hardcoded path, because the box's checkout is not
# where the repo's own instructions assume, and a wrong path reads exactly like a
# missing file or a missing guard.
repo_root="${KYRIAKON_REPO:-/usr/local/src/kyriakon-infra}"

# --- 1. permission and ownership drift -----------------------------------
if [ "$(id -u)" -eq 0 ]; then
	drift=$(mtree -q -f /etc/mtree/special -p / 2>&1 \
		| grep -E '^(mode|uid|gid|type|size|link)' || true)
	if [ -n "$drift" ]; then
		printf 'permissions: drift from /etc/mtree/special\n%s\n' "$drift"
		status=1
	else
		printf 'permissions: no drift from /etc/mtree/special\n'
	fi
else
	printf 'permissions: skipped, needs root to read /etc/mtree/special\n'
fi

# --- 2. blocklist --------------------------------------------------------
ip="${PUBLIC_IP:-$(ifconfig egress inet 2>/dev/null | awk '/inet / { print $2; exit }')}"
if [ -z "$ip" ]; then
	printf 'blocklist: cannot determine this box address\n'
	# Not a clean run: an address that could not be determined was not checked.
	status=1
	exit "$status"
fi
verdict=$(dnsbl_verdict "$ip")
case "$verdict" in
listed*)
	printf 'blocklist: %s is listed: %s. That names the list and the code; look it up and request removal\n' \
		"$ip" "${verdict#listed }"
	status=1
	;;
clean*)
	printf 'blocklist: %s is not listed on %s\n' "$ip" "${verdict#clean }"
	;;
*)
	printf 'blocklist: %s. A listing would go unnoticed until one answers\n' "$verdict"
	status=1
	;;
esac

# Which resolver answered is worth knowing on its own: Spamhaus, the list that matters
# for deliverability, only answers one that serves a single machine, so its absence
# silently downgrades the verdict to a weaker zone rather than failing the check.
if dig +short +time=2 +tries=1 @127.0.0.1 . NS >/dev/null 2>&1; then
	printf 'blocklist: asked through the resolver on this box, which Spamhaus answers\n'
else
	printf 'blocklist: no resolver on this box, so Spamhaus refuses and the fallback zones carry the verdict. unbound ships in base\n'
fi

# --- 3. does the cron environment still reach the tools cron needs? ------
# cron(8) gives jobs PATH=/usr/bin:/bin. Packages live in /usr/local and ifconfig
# in /sbin, so a job that does not put those back finds neither, and
# abuse-monitor.sh's Healthchecks ping is `curl ... || true`, which turns that
# into a failure indistinguishable from a clean run: the box looks monitored
# while no ping is being sent. Source the env exactly as a cron line does, on
# cron's PATH, and ask what a job would find.
if [ "$(id -u)" -eq 0 ] && [ -f /root/.kyriakon-env ]; then
	absent=""
	tools="curl ifconfig hcloud jq"
	for tool in $tools; do
		env -i PATH=/usr/bin:/bin sh -c ". /root/.kyriakon-env; command -v $tool" >/dev/null 2>&1 \
			|| absent="$absent $tool"
	done
	if [ -n "$absent" ]; then
		printf 'cron environment: a cron job would not find:%s\n' "$absent"
		printf '  the fix is the PATH line in /root/.kyriakon-env, which every cron line sources\n'
		# shellcheck disable=SC2086 # the word list the loop above just built
		tool_remedy $absent
		status=1
	else
		printf 'cron environment: %s all reachable as a cron job sees them\n' "$tools"
	fi
else
	printf 'cron environment: skipped, needs root and /root/.kyriakon-env\n'
fi

# --- 4. finger -----------------------------------------------------------
# Served by fingerd under inetd from a page the mail deploy generates. Reads
# nothing secret, so this section needs no root guard: the page is world-readable
# by design, since _fingerd is what reads it.
finger_page=/etc/kyriakon/finger.txt
finger_provider=/usr/local/libexec/kyriakon-finger
if [ -f "$finger_page" ] && [ -s "$finger_page" ]; then
	# The endpoint lines are the indented ones, so this is the count that matters
	# rather than the line count. grep -c returns non-zero at zero matches, which
	# under set -e would end the script before it could report the problem.
	endpoints=$(grep -c '^  ' "$finger_page" || true)
	printf 'finger: page present, %s endpoint lines\n' "$endpoints"
	if [ "$endpoints" -eq 0 ]; then
		printf 'finger: the page carries no endpoints; httpd.conf and gmid.conf are the source\n'
		status=1
	fi
else
	printf 'finger: %s missing or empty; the mail deploy installs it\n' "$finger_page"
	status=1
fi
if [ -x "$finger_provider" ]; then
	printf 'finger: provider installed and executable\n'
else
	printf 'finger: %s missing or not executable; port 79 would answer nothing\n' "$finger_provider"
	status=1
fi
# Both families, because inetd takes the socket family from the protocol field and
# a single `tcp` line leaves the IPv6 address refusing connections. Checking only
# that some finger line exists is what let the first version of this ship half-open.
if [ -f /etc/inetd.conf ]; then
	for proto in tcp tcp6; do
		if grep -Eq "^[[:space:]]*finger[[:space:]]+stream[[:space:]]+${proto}[[:space:]]" /etc/inetd.conf; then
			printf 'finger: inetd line present (%s)\n' "$proto"
		else
			printf 'finger: no finger/%s line in /etc/inetd.conf; that family is dark\n' "$proto"
			status=1
		fi
	done
else
	printf 'finger: /etc/inetd.conf is missing; port 79 is dark on both families\n'
	status=1
fi
# --- 5. the shared service catalogue -------------------------------------
# The catalogue is one file the three front-ends read, and the box's copy is
# installed from a checkout (scripts/onboard-store.sh). A deployed copy that
# differs from the tracked one is a rendering nobody reviewed, whichever
# direction it differs in: a hand edit on the box, or a deploy that never ran
# after the file changed. The comparison is the file's bytes rather than a
# rendering of it, because the point of the file is that it is the same file
# everywhere, and a diff here is what a person reads to see which way.
catalogue="$repo_root/openbsd/etc/onboard/catalogue.toml"
deployed_catalogue=/var/db/onboard/catalogue.toml
if [ ! -f "$deployed_catalogue" ]; then
	printf 'catalogue: %s is missing; scripts/onboard-store.sh installs it\n' "$deployed_catalogue"
	status=1
elif cmp -s "$catalogue" "$deployed_catalogue"; then
	printf 'catalogue: the deployed copy matches the tracked one\n'
else
	printf 'catalogue: %s differs from %s, or one of the two is unreadable; the front-ends render the deployed copy, so rerun scripts/onboard-store.sh from this checkout\n' \
		"$deployed_catalogue" "$catalogue"
	status=1
fi

# --- 6. terraform --------------------------------------------------------
# The repo's one automated path is the weekly restore standup, which now drives the
# Hetzner API with the hcloud CLI and deletes only the server id it created that run. The
# refusals in front of a mistaken destroy are the id discipline in that script, the live
# root's prevent_destroy, and Hetzner's delete_protection. Only the second is checked
# here, because it is the one that lives in a file that can silently lose it.
#
# The path is a variable rather than hardcoded, because the box's checkout is not where
# the repo's own instructions assume and a wrong path reads exactly like a missing guard.
# It is set once at the top of this script, where the catalogue's comparison reads it too.
tf_dir="$repo_root/terraform"
if grep -q 'prevent_destroy[[:space:]]*=[[:space:]]*true' "$tf_dir/main.tf" 2>/dev/null; then
	printf 'terraform: the live root refuses to plan the removal of its server\n'
else
	printf 'terraform: no prevent_destroy in %s/main.tf; only delete_protection would stand between a bad plan and the mail box\n' "$tf_dir"
	status=1
fi
# The restore image is what the weekly run creates its box from, so an absent or
# mislabelled one means the test cannot run. Checked by looking for the image, which is
# what the standup does too, rather than by trusting a label convention in a document.
# The token lives in the box's env file, which this script does not source into its own
# environment, so it is read the way the cron PATH check reads it: in a subshell that
# sources that file and nothing else.
if [ "$(id -u)" -eq 0 ] && [ -f /root/.kyriakon-env ]; then
	restore_image=$(env -i PATH=/usr/bin:/bin:/usr/local/bin sh -c \
		". /root/.kyriakon-env; hcloud image list -t snapshot -l ${RESTORE_TEST_IMAGE_LABEL:-kind=restore} -o noheader -o columns=id" 2>/dev/null | head -1)
	if [ -n "$restore_image" ]; then
		printf 'terraform: a snapshot labelled %s exists, so the weekly test has a template\n' "${RESTORE_TEST_IMAGE_LABEL:-kind=restore}"
	else
		printf 'terraform: no snapshot labelled %s; the weekly restore test has no template to create from\n' "${RESTORE_TEST_IMAGE_LABEL:-kind=restore}"
		status=1
	fi
else
	printf 'terraform: hcloud and the env file are both needed to check the restore image\n'
	status=1
fi

# --- 7. the two files that name the mail domains --------------------------
# smtpd accepts mail for every domain in mail_domains, and spamd's greylist
# pass-through list is what decides which destinations it lets through. The two
# are written by different steps and only the first is generated: deploy-mail.sh
# seeds the platform's own domain into it, and the drain appends a body's domain
# as it provisions one, while spamd.alloweddomains is installed once from the
# tracked file and nothing rewrites it. A domain in the first and not the second
# is not mail that is delayed: spamd(8) traps it and puts the sending host on the
# blocklist, wherever the greylist diverts are in place, so the failure is seen
# by whoever writes to that parish and not by anything here. The allow list's own
# header says the same, which is what made the pair worth checking rather than
# trusting.
mail_domains_table=/etc/mail/mail_domains
spamd_allowed=/etc/mail/spamd.alloweddomains
if [ ! -f "$mail_domains_table" ]; then
	printf 'mail domains: %s is missing; scripts/deploy-mail.sh seeds it with the platform domain\n' \
		"$mail_domains_table"
	status=1
elif [ ! -f "$spamd_allowed" ]; then
	printf 'mail domains: %s is missing; it is installed from openbsd/etc/spamd.alloweddomains\n' \
		"$spamd_allowed"
	status=1
else
	unwelcome=$(domains_missing_from "$mail_domains_table" "$spamd_allowed")
	if [ -n "$unwelcome" ]; then
		printf 'mail domains: %s names these and %s has no line for them, so spamd traps them and blocklists the sender:\n' \
			"$mail_domains_table" "$spamd_allowed"
		printf '%s\n' "$unwelcome" | sed -e 's/^/  /'
		printf '  the line it wants is @<domain>; add it and reload spamd\n'
		status=1
	else
		printf 'mail domains: every domain smtpd accepts is in the greylist pass-through list\n'
	fi
fi

# --- 8. the address every alert is mailed to ------------------------------
# notify_operator in lib.sh mails this address and prints when it cannot. The
# print is the fallback, not the plan: cron mails it under its own subject, where
# the component and the event are gone. The file is root's, so this half runs on
# the box as root or not at all.
env_file="${KYRIAKON_ENV:-/root/.kyriakon-env}"
if [ ! -r "$env_file" ]; then
	printf 'alert address: %s is unreadable, so whether an alert can leave the box is unchecked (needs root)\n' \
		"$env_file"
	status=1
else
	address_problem=$(alert_address_problem "$env_file" "$mail_domains_table")
	if [ -n "$address_problem" ]; then
		printf 'alert address: %s\n' "$address_problem"
		printf '  set it with scripts/setup-env.sh --alert-email <address>, at an address off this box\n'
		status=1
	else
		printf 'alert address: set, and off this box\n'
	fi
fi

# --- 9. the scripts the box runs are the scripts the checkout has ---------
# The deploys copy scripts into /root/bin and the drain's directory, and nothing
# reads them again afterwards. A box running copies older than its checkout gives
# no sign at all: operator mail went out without the subject fix for months, and
# it surfaced because someone happened to look at a subject line.
repo_dir="${KYRIAKON_REPO:-/usr/local/src/kyriakon-infra}"
if [ -d "$repo_dir/scripts" ]; then
	drift=$(deployed_drift "$repo_dir/scripts" /root/bin /usr/local/libexec/kyriakon/scripts)
	if [ -n "$drift" ]; then
		printf 'installed scripts: these are not the checkout at %s/scripts:\n' "$repo_dir"
		printf '%s\n' "$drift" | sed -e 's/^/  /'
		printf '  the fix is the deploy that installs them: deploy-mail.sh for /root/bin, deploy-onboard.sh for the drain\n'
		status=1
	else
		printf 'installed scripts: every copy matches the checkout\n'
	fi
else
	printf 'installed scripts: no checkout at %s/scripts, so this was skipped\n' "$repo_dir"
fi

# --- 10. the store's records belong to the handler ------------------------
# The handler renders the status page from applications/ and runs as _onboard. A
# record left root-owned reads as missing to it, which is why the drain hands each
# one back to the directory's owner after it writes.
applications_dir=/var/db/onboard/applications
if [ -d "$applications_dir" ]; then
	owner_drift=$(store_drift "$applications_dir" _onboard)
	if [ -n "$owner_drift" ]; then
		printf 'store records: these are not owned by _onboard, so the handler cannot read them:\n'
		printf '%s\n' "$owner_drift" | sed -e 's/^/  /'
		printf '  the fix is chown _onboard, and the writer that made them: the drain must use write_record_owned\n'
		status=1
	else
		printf "store records: every application record belongs to the handler\n"
	fi
else
	printf 'store records: %s is gone\n' "$applications_dir"
	status=1
fi

exit "$status"
